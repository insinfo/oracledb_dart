@Tags(['integration'])
library;

import 'dart:typed_data';

import 'package:oracledb_dart/oracledb_dart.dart';
import 'package:test/test.dart';

import 'helpers.dart';

void main() {
  group('JSON and VECTOR', skip: OracleTestConfig.skipReason, () {
    final conn = sharedConnection();
    final doc = {
      'id': 1,
      'name': 'Ada',
      'score': 9.5,
      'tags': ['math', 'computing'],
      'address': {'city': 'London', 'zip': null},
      'active': true,
    };

    test('native JSON columns', () async {
      await dropTable(conn(), 'dart_json_t');
      await conn().execute('create table dart_json_t (id number, data json)');
      await conn().execute('insert into dart_json_t values (1, :1)', [doc]);
      await conn().executeMany('insert into dart_json_t values (:1, :2)', [
        [
          2,
          [1, 2, 3]
        ],
        [3, 'a string document'],
        [4, null],
      ]);
      final rows =
          await conn().query('select data from dart_json_t order by id');
      expect(rows[0][0], doc);
      expect(rows[1][0], [1, 2, 3]);
      expect(rows[2][0], 'a string document');
      expect(rows[3][0], isNull);
      final city = await conn().queryOne(
          "select json_value(data, '\$.address.city') from dart_json_t where id = 1");
      expect(city![0], 'London');
      // JSON generated by the server
      final generated = await conn().queryOne(
          "select json_object('a' value 1, 'b' value json_array(1, 'x' , true) "
          'returning json) from dual');
      expect(generated![0], {
        'a': 1,
        'b': [1, 'x', true]
      });
      await dropTable(conn(), 'dart_json_t');
    });

    test('text columns with an IS JSON constraint are decoded', () async {
      await dropTable(conn(), 'dart_isjson_t');
      await conn().execute('create table dart_isjson_t ('
          'v varchar2(200) check (v is json), c clob check (c is json))');
      await conn().execute('insert into dart_isjson_t values (:1, :2)',
          ['{"x": [1, 2]}', '{"big": "${'z' * 5000}"}']);
      final row = await conn().queryOne('select v, c from dart_isjson_t');
      expect(row![0], {
        'x': [1, 2]
      });
      expect((row[1] as Map)['big'], 'z' * 5000);
      await dropTable(conn(), 'dart_isjson_t');
    });

    test('VECTOR columns', () async {
      if (conn().serverVersion.first < 23) return;
      await dropTable(conn(), 'dart_vec_t');
      await conn().execute('create table dart_vec_t (id number, '
          'v32 vector(3, float32), v64 vector(2, float64), v8 vector(4, int8), '
          'vb vector(16, binary), vs vector(10, float32, sparse))');
      final sparse = SparseVector(10, [0, 9], Float32List.fromList([1.5, -1]));
      await conn()
          .execute('insert into dart_vec_t values (1, :1, :2, :3, :4, :5)', [
        Float32List.fromList([1.5, 2.5, -3]),
        Float64List.fromList([1e10, -2]),
        Int8List.fromList([1, -2, 3, -4]),
        BinaryVector(Uint8List.fromList([0xff, 0x01])),
        sparse,
      ]);
      final row =
          await conn().queryOne('select v32, v64, v8, vb, vs from dart_vec_t');
      expect(row![0], Float32List.fromList([1.5, 2.5, -3]));
      expect(row[1], Float64List.fromList([1e10, -2]));
      expect(row[2], Int8List.fromList([1, -2, 3, -4]));
      expect(row[3], Uint8List.fromList([0xff, 0x01]));
      expect(row[4], sparse);
      final distance = await conn().queryOne(
          "select vector_distance(v32, to_vector('[1.5, 2.5, -3]', 3, float32)) "
          'from dart_vec_t');
      expect(distance![0], 0);
      await dropTable(conn(), 'dart_vec_t');
    });
  });
}
